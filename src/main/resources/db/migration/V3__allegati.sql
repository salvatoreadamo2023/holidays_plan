-- Allegati alle assenze (certificati, giustificativi). File piccoli, salvati nel DB.
CREATE TABLE request_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    filename VARCHAR(150) NOT NULL,
    content_type VARCHAR(60) NOT NULL,
    size_bytes BIGINT NOT NULL,
    data BYTEA NOT NULL,
    uploaded_by_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_att_request FOREIGN KEY (request_id) REFERENCES absence_requests (id),
    CONSTRAINT fk_att_user FOREIGN KEY (uploaded_by_id) REFERENCES users (id)
);
CREATE INDEX ix_att_request ON request_attachments (request_id);
